CLD
CMP SP,0FFFEH
JE I_ENTRY
MOV AX,4C07H
INT 21H
I_ENTRY:
JMP U_MAIN
U_F0:
DB 79
U_F1:
DB 85
U_F2:
DB 84
U_F3:
DB 46
U_F4:
DB 84
U_F5:
DB 88
U_F6:
DB 84
U_F7:
DB 0
U_MAIN:
MOV AX,U_F0
CALL R_CREATE
MOV AX,[R_STATUS]
MOV AH,4CH
INT 21H
R_OK:
MOV DX,0
MOV [R_STATUS],DX
RET
R_ERROR:
MOV DX,1
MOV [R_STATUS],DX
RET
R_FAIL:
MOV AX,0
JMP R_ERROR

R_PUTC:
MOV [R_BYTE],AL
MOV BX,1
MOV CX,1
MOV DX,R_BYTE
MOV AH,40H
INT 21H
JAE R_PUTCOUNT
JMP R_FAIL
R_PUTCOUNT:
CMP AX,1
JE R_PUTGOOD
JMP R_ERROR
R_PUTGOOD:
JMP R_OK

R_GETC:
MOV BX,0
MOV CX,1
MOV DX,R_BYTE
MOV AH,3FH
INT 21H
JAE R_GETCOUNT
MOV AX,65535
JMP R_ERROR
R_GETCOUNT:
CMP AX,0
JNE R_GETBYTE
MOV AX,65535
JMP R_OK
R_GETBYTE:
MOV AL,[R_BYTE]
MOV AH,0
JMP R_OK

R_OPEN:
MOV DX,3D00H
JMP R_FILE

R_CREATE:
MOV DX,3C00H
JMP R_FILE

R_FILE:
MOV [R_MODE],DX
MOV [R_NAME],AX
CALL R_FREE
CMP BX,0
JNE R_HAVESLOT
JMP R_FAIL
R_HAVESLOT:
MOV DX,[R_NAME]
MOV CX,0
MOV AX,[R_MODE]
INT 21H
JAE R_FILEGOOD
JMP R_FAIL
R_FILEGOOD:
INC AX
MOV DX,[R_MODE]
CMP DX,3C00H
JNE R_READSLOT
ADD AX,8000H
R_READSLOT:
MOV BX,[R_SLOT]
MOV [BX],AX
MOV AX,[R_NUMBER]
JMP R_OK
R_FREE:
MOV BX,R_HANDLES
MOV CX,1
R_NEXTSLOT:
MOV AX,[BX]
CMP AX,0
JE R_SLOTFOUND
ADD BX,2
INC CX
CMP CX,9
JB R_NEXTSLOT
MOV BX,0
RET
R_SLOTFOUND:
MOV [R_SLOT],BX
MOV [R_NUMBER],CX
RET

R_STATUS:
DW 0

R_BYTE:
DB 0

R_MODE:
DW 0
R_NAME:
DW 0
R_SLOT:
DW 0
R_NUMBER:
DW 0
R_HANDLES:
DW 0,0,0,0,0,0,0,0
