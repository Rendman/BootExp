CLD
CMP SP,0FFFEH
JE I_ENTRY
MOV AX,4C07H
INT 21H
I_ENTRY:
JMP U_MAIN
U_F0:
DB 73
U_F1:
DB 78
U_F2:
DB 46
U_F3:
DB 84
U_F4:
DB 88
U_F5:
DB 84
U_F6:
DB 0
U_HANDLE:
DW 0
U_COUNT:
DW 0
U_DATA:
DB 0
U_MAIN:
MOV AX,U_F0
CALL R_OPEN
MOV [U_HANDLE],AX
MOV AX,[R_STATUS]
CMP AX,0
JE I0001
JMP U_FAILURE
I0001:
MOV AX,[U_HANDLE]
PUSH AX
MOV AX,U_DATA
PUSH AX
MOV AX,1
POP DX
POP BX
CALL R_READ
MOV [U_COUNT],AX
MOV AX,[R_STATUS]
CMP AX,0
JE I0002
JMP U_FAILURE
I0002:
MOV AX,[U_COUNT]
PUSH AX
MOV AX,1
POP BX
CMP BX,AX
JE I0003
JMP U_FAILURE
I0003:
MOV AX,U_DATA
MOV BX,AX
MOV AL,[BX]
MOV AH,0
CALL R_PUTC
MOV AX,[R_STATUS]
MOV AH,4CH
INT 21H
U_FAILURE:
MOV AX,1
MOV AH,4CH
INT 21H
R_OK:
MOV DX,0
MOV [R_STATUS],DX
RET
R_ERROR:
MOV DX,1
MOV [R_STATUS],DX
RET
R_FAIL:
MOV AX,0
JMP R_ERROR

R_PUTC:
MOV [R_BYTE],AL
MOV BX,1
MOV CX,1
MOV DX,R_BYTE
MOV AH,40H
INT 21H
JAE R_PUTCOUNT
JMP R_FAIL
R_PUTCOUNT:
CMP AX,1
JE R_PUTGOOD
JMP R_ERROR
R_PUTGOOD:
JMP R_OK

R_GETC:
MOV BX,0
MOV CX,1
MOV DX,R_BYTE
MOV AH,3FH
INT 21H
JAE R_GETCOUNT
MOV AX,65535
JMP R_ERROR
R_GETCOUNT:
CMP AX,0
JNE R_GETBYTE
MOV AX,65535
JMP R_OK
R_GETBYTE:
MOV AL,[R_BYTE]
MOV AH,0
JMP R_OK

R_OPEN:
MOV DX,3D00H
JMP R_FILE

R_CREATE:
MOV DX,3C00H
JMP R_FILE

R_FILE:
MOV [R_MODE],DX
MOV [R_NAME],AX
CALL R_FREE
CMP BX,0
JNE R_HAVESLOT
JMP R_FAIL
R_HAVESLOT:
MOV DX,[R_NAME]
MOV CX,0
MOV AX,[R_MODE]
INT 21H
JAE R_FILEGOOD
JMP R_FAIL
R_FILEGOOD:
INC AX
MOV DX,[R_MODE]
CMP DX,3C00H
JNE R_READSLOT
ADD AX,8000H
R_READSLOT:
MOV BX,[R_SLOT]
MOV [BX],AX
MOV AX,[R_NUMBER]
JMP R_OK
R_FREE:
MOV BX,R_HANDLES
MOV CX,1
R_NEXTSLOT:
MOV AX,[BX]
CMP AX,0
JE R_SLOTFOUND
ADD BX,2
INC CX
CMP CX,9
JB R_NEXTSLOT
MOV BX,0
RET
R_SLOTFOUND:
MOV [R_SLOT],BX
MOV [R_NUMBER],CX
RET

R_FIND:
CMP BX,1
JB R_BADHANDLE
CMP BX,8
JA R_BADHANDLE
DEC BX
ADD BX,BX
ADD BX,R_HANDLES
MOV [R_SLOT],BX
MOV BX,[BX]
CMP BX,0
JE R_BADHANDLE
MOV AX,1
CMP BX,8000H
JB R_HANDLEKIND
AND BX,7FFFH
MOV AX,2
R_HANDLEKIND:
DEC BX
RET
R_BADHANDLE:
MOV AX,0
RET

R_READ:
MOV [R_COUNT],AX
MOV [R_BUFFER],DX
CALL R_FIND
CMP AX,1
JE R_READVALID
JMP R_FAIL
R_READVALID:
MOV CX,[R_COUNT]
CMP CX,0
JNE R_READMORE
MOV AX,0
JMP R_OK
R_READMORE:
MOV DX,[R_BUFFER]
MOV AH,3FH
INT 21H
JAE R_READGOOD
JMP R_FAIL
R_READGOOD:
JMP R_OK

R_STATUS:
DW 0

R_BYTE:
DB 0

R_MODE:
DW 0
R_NAME:
DW 0
R_SLOT:
DW 0
R_NUMBER:
DW 0
R_HANDLES:
DW 0,0,0,0,0,0,0,0

R_COUNT:
DW 0
R_BUFFER:
DW 0
