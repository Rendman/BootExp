START:
CLD
CMP SP,0FFFEH
JE ROOM
MOV AX,7
JMP ERROR
ROOM:
CALL OPENFILE
DUMPBYTE:
CALL NEXTBYTE
CMP AX,0
JE DUMPEND
MOV DL,[CHAR]
MOV AH,2
INT 21H
JMP DUMPBYTE
DUMPEND:
CALL CLOSEFILE
GOOD:
MOV AX,4C00H
INT 21H

FILEBAD:
MOV AX,6
JMP ERROR

OPENFILE:
MOV DX,FNAME
MOV AX,3D00H
INT 21H
JAE INPUTOPEN
JMP FILEBAD
INPUTOPEN:
MOV [HANDLE],AX
RET

CLOSEFILE:
MOV BX,[HANDLE]
MOV AH,3EH
INT 21H
JB FILEBAD
RET

NEXTBYTE:
MOV BX,[HANDLE]
MOV CX,1
MOV DX,CHAR
MOV AH,3FH
INT 21H
JAE BYTEOK
MOV AX,6
JMP ERROR
BYTEOK:
RET

TEXT:
MOV AH,9
INT 21H
RET

NUMBER:
PUSH AX
PUSH BX
PUSH CX
PUSH DX
PUSH SI
MOV CX,AX
MOV SI,DIVISORS
NEXTPLACE:
MOV BX,SI
MOV DX,[BX]
MOV AL,48
SUBTRACT:
CMP CX,DX
JB PRINTDIGIT
SUB CX,DX
ADD AL,1
JMP SUBTRACT
PRINTDIGIT:
MOV DL,AL
MOV AH,2
INT 21H
ADD SI,2
CMP SI,DIVEND
JB NEXTPLACE
POP SI
POP DX
POP CX
POP BX
POP AX
RET

