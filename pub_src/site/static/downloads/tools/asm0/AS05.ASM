MOV [ERRCODE],AL
MOV DX,ERRMSG
CALL TEXT
MOV AX,[LINENO]
CALL NUMBER
MOV DX,CODEMSG
CALL TEXT
MOV AL,[ERRCODE]
ADD AL,48
MOV DL,AL
MOV AH,2
INT 21H
MOV DX,NEWLINE
CALL TEXT
MOV AX,4C01H
INT 21H

