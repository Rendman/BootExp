CLD
CMP SP,0FFFEH
JE I_ENTRY
MOV AX,4C07H
INT 21H
I_ENTRY:
JMP U_MAIN
U_MAIN:
MOV AX,73
CALL R_PUTC
MOV AX,99
MOV AX,[R_STATUS]
MOV AH,4CH
INT 21H
R_OK:
MOV DX,0
MOV [R_STATUS],DX
RET
R_ERROR:
MOV DX,1
MOV [R_STATUS],DX
RET
R_FAIL:
MOV AX,0
JMP R_ERROR

R_PUTC:
MOV [R_BYTE],AL
MOV BX,1
MOV CX,1
MOV DX,R_BYTE
MOV AH,40H
INT 21H
JAE R_PUTCOUNT
JMP R_FAIL
R_PUTCOUNT:
CMP AX,1
JE R_PUTGOOD
JMP R_ERROR
R_PUTGOOD:
JMP R_OK

R_STATUS:
DW 0

R_BYTE:
DB 0
