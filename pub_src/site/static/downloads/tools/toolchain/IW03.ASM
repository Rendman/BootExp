START:
CLD
CMP SP,0FFFEH
JNE NEAR MEMORYBAD
CALL PREFLIGHT
CALL OPENFILE
CALL CREATEOUT
COPYBYTE:
CALL NEXTBYTE
CMP AX,0
JE NEAR COPYDONE
MOV AL,[CHAR]
CALL EMITCHAR
JMP COPYBYTE
COPYDONE:
CALL CLOSEFILE
CALL FLUSH
CALL CLOSEOUT
CALL COMMIT
MOV DX,OKMSG
CALL TEXT
MOV AX,[TOTALLO]
MOV DX,[TOTALHI]
CALL NUMBER32
MOV DX,BYTEMSG
CALL TEXT
MOV AX,4C00H
INT 21H
MEMORYBAD:
MOV AX,7
JMP ERROR

FILEBAD:
MOV AX,6
JMP ERROR

OPENFILE:
MOV DX,SRCNAME
MOV AX,3D00H
INT 21H
JAE NEAR INPUTOPEN
JMP FILEBAD
INPUTOPEN:
MOV [HANDLE],AX
MOV AL,1
MOV [INOPEN],AL
RET

CLOSEFILE:
MOV BX,[HANDLE]
MOV AH,3EH
INT 21H
JAE NEAR INPUTCLOSED
JMP FILEBAD
INPUTCLOSED:
MOV AL,0
MOV [INOPEN],AL
RET

CREATEOUT:
MOV DX,TMPNAME
MOV CX,0
MOV AH,3CH
INT 21H
JAE NEAR OUTPUTOPEN
JMP FILEBAD
OUTPUTOPEN:
MOV [OUTHANDLE],AX
MOV AL,1
MOV [OUTOPEN],AL
MOV [OWNTMP],AL
RET
CLOSEOUT:
MOV BX,[OUTHANDLE]
MOV AH,3EH
INT 21H
JAE NEAR OUTPUTCLOSED
JMP FILEBAD
OUTPUTCLOSED:
MOV AL,0
MOV [OUTOPEN],AL
RET

FLUSH:
PUSH AX
PUSH BX
PUSH CX
PUSH DX
MOV CX,[OUTCNT]
CMP CX,0
JE NEAR FLUSHDONE
MOV BX,[OUTHANDLE]
MOV DX,0E000H
MOV AH,40H
INT 21H
JAE NEAR FLUSHCOUNT
JMP FILEBAD
FLUSHCOUNT:
CMP AX,CX
JE NEAR FLUSHGOOD
JMP FILEBAD
FLUSHGOOD:
MOV AX,0
MOV [OUTCNT],AX
FLUSHDONE:
POP DX
POP CX
POP BX
POP AX
RET

NEXTBYTE:
MOV AX,[RDPOS]
MOV DX,[RDLEN]
CMP AX,DX
JB NEAR BUFFERBYTE
MOV BX,[HANDLE]
MOV DX,0D000H
MOV CX,4096
MOV AH,3FH
INT 21H
JAE NEAR REFILLED
JMP FILEBAD
REFILLED:
MOV [RDLEN],AX
MOV DX,0
MOV [RDPOS],DX
CMP AX,0
JE NEAR BUFFEREND
BUFFERBYTE:
MOV BX,[RDPOS]
ADD BX,0D000H
MOV AL,[BX]
MOV [CHAR],AL
MOV AX,[RDPOS]
INC AX
MOV [RDPOS],AX
CALL COUNTINPUT
MOV AX,1
RET
BUFFEREND:
MOV AX,0
RET

TEXT:
MOV AH,9
INT 21H
RET

ERROR:
MOV [ERRCODE],AL
CALL CLEANUP
MOV DX,ERRMSG
CALL TEXT
MOV AX,[LINENO]
MOV DX,[LINEHI]
CALL NUMBER32
MOV DX,CODEMSG
CALL TEXT
MOV AL,[ERRCODE]
ADD AL,48
MOV DL,AL
MOV AH,2
INT 21H
MOV DX,NEWLINE
CALL TEXT
MOV AL,[CLEANFAIL]
MOV DL,[KEEPFILES]
OR AL,DL
MOV DL,[HAVEBAK]
OR AL,DL
CMP AL,0
JE NEAR ERROREXIT
MOV DX,RECOVERMSG
CALL TEXT
ERROREXIT:
MOV AX,4C01H
INT 21H

EXISTS:
MOV AX,3D00H
INT 21H
JAE NEAR FILEEXISTS
CMP AX,2
JE NEAR FILENONE
JMP FILEBAD
FILEEXISTS:
MOV BX,AX
MOV AH,3EH
INT 21H
JAE NEAR EXISTSCLOSED
JMP FILEBAD
EXISTSCLOSED:
MOV AX,1
RET
FILENONE:
MOV AX,0
RET
PREFLIGHT:
MOV DX,TMPNAME
CALL EXISTS
CMP AX,0
JNE NEAR NAMEBUSY
MOV DX,BAKNAME
CALL EXISTS
CMP AX,0
JE NEAR PREFLIGHTOK
NAMEBUSY:
MOV AX,8
JMP ERROR
PREFLIGHTOK:
RET

COMMIT:
MOV DX,RESNAME
CALL EXISTS
CMP AX,0
JE NEAR PUBLISH
MOV DX,RESNAME
MOV DI,BAKNAME
MOV AH,56H
INT 21H
JAE NEAR BACKEDUP
JMP FILEBAD
BACKEDUP:
MOV AL,1
MOV [HAVEBAK],AL
PUBLISH:
MOV DX,TMPNAME
MOV DI,RESNAME
MOV AH,56H
INT 21H
JAE NEAR PUBLISHED
MOV AL,[HAVEBAK]
CMP AL,0
JE NEAR PUBLISHFAIL
MOV DX,BAKNAME
MOV DI,RESNAME
MOV AH,56H
INT 21H
JAE NEAR RESTORED
MOV AL,1
MOV [KEEPFILES],AL
JMP PUBLISHFAIL
RESTORED:
MOV AL,0
MOV [HAVEBAK],AL
PUBLISHFAIL:
JMP FILEBAD
PUBLISHED:
MOV AL,0
MOV [OWNTMP],AL
MOV AL,[HAVEBAK]
CMP AL,0
JE NEAR COMMITDONE
MOV DX,BAKNAME
MOV AH,41H
INT 21H
JAE NEAR BACKREMOVED
JMP FILEBAD
BACKREMOVED:
MOV AL,0
MOV [HAVEBAK],AL
COMMITDONE:
RET

CLEANUP:
MOV AL,[INOPEN]
CMP AL,0
JE NEAR CLEANOUTPUT
MOV BX,[HANDLE]
MOV AH,3EH
INT 21H
JAE NEAR CLEANOUTPUT
MOV AL,1
MOV [CLEANFAIL],AL
CLEANOUTPUT:
MOV AL,[OUTOPEN]
CMP AL,0
JE NEAR CLEANTEMP
MOV BX,[OUTHANDLE]
MOV AH,3EH
INT 21H
JAE NEAR CLEANTEMP
MOV AL,1
MOV [CLEANFAIL],AL
CLEANTEMP:
MOV AL,[OWNTMP]
CMP AL,0
JE NEAR CLEANEND
MOV AL,[KEEPFILES]
CMP AL,0
JNE NEAR CLEANEND
MOV DX,TMPNAME
MOV AH,41H
INT 21H
JAE NEAR CLEANEND
MOV AL,1
MOV [CLEANFAIL],AL
CLEANEND:
RET

COUNTLINE:
MOV AX,[LINENO]
CMP AX,0FFFFH
JNE NEAR LINELOW
MOV AX,[LINEHI]
CMP AX,0FFFFH
JE NEAR COUNTFULL
INC AX
MOV [LINEHI],AX
MOV AX,0
MOV [LINENO],AX
RET
LINELOW:
INC AX
MOV [LINENO],AX
RET
COUNTFULL:
MOV AX,5
JMP ERROR

COUNTINPUT:
MOV AX,[INBYTES]
CMP AX,0FFFFH
JNE NEAR INPUTLOW
MOV AX,[INBYTEHI]
CMP AX,0FFFFH
JE NEAR COUNTFULL
INC AX
MOV [INBYTEHI],AX
MOV AX,0
MOV [INBYTES],AX
RET
INPUTLOW:
INC AX
MOV [INBYTES],AX
RET

NUMBER32:
PUSH AX
PUSH BX
PUSH CX
PUSH DX
PUSH SI
MOV [N32LO],AX
MOV [N32HI],DX
MOV SI,DIV32
N32PLACE:
MOV BX,SI
MOV AX,[BX]
MOV [D32HI],AX
ADD BX,2
MOV AX,[BX]
MOV [D32LO],AX
MOV CX,0
N32SUB:
MOV AX,[N32HI]
MOV DX,[D32HI]
CMP AX,DX
JB NEAR N32DIGIT
JA NEAR N32TAKE
MOV AX,[N32LO]
MOV DX,[D32LO]
CMP AX,DX
JB NEAR N32DIGIT
N32TAKE:
MOV AX,[N32LO]
MOV DX,[D32LO]
SUB AX,DX
MOV [N32LO],AX
JAE NEAR N32NOBORROW
MOV AX,[N32HI]
DEC AX
MOV [N32HI],AX
N32NOBORROW:
MOV AX,[N32HI]
MOV DX,[D32HI]
SUB AX,DX
MOV [N32HI],AX
INC CX
JMP N32SUB
N32DIGIT:
MOV DL,CL
ADD DL,48
MOV AH,2
INT 21H
ADD SI,4
CMP SI,DIV32END
JB NEAR N32PLACE
POP SI
POP DX
POP CX
POP BX
POP AX
RET

EMITCHAR:
PUSH BX
MOV BX,[OUTCNT]
ADD BX,0E000H
MOV [BX],AL
MOV BX,[TOTALLO]
INC BX
MOV [TOTALLO],BX
CMP BX,0
JNE NEAR COUNTGOOD
MOV BX,[TOTALHI]
INC BX
MOV [TOTALHI],BX
CMP BX,0
JE NEAR TABLEFULL
COUNTGOOD:
MOV BX,[OUTCNT]
INC BX
MOV [OUTCNT],BX
CMP BX,4096
JNE NEAR CHARDONE
CALL FLUSH
CHARDONE:
POP BX
RET

BALANCED:
MOV AX,[DEPTH]
CMP AX,0
JNE NEAR STACKBAD
RET
STACKBAD:
MOV AX,4
JMP ERROR
SYNTAXBAD:
MOV AX,1
JMP ERROR
TABLEFULL:
MOV AX,5
JMP ERROR

