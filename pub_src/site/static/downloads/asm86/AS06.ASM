START:
CLD
CMP SP,0FFFEH
JE ROOM
MOV AX,7
JMP ERROR
ROOM:
CALL GETNAME
CALL OPENFILE
DUMPBYTE:
CALL NEXTBYTE
CMP AX,0
JE DUMPEND
MOV DL,[CHAR]
MOV AH,2
INT 21H
JMP DUMPBYTE
DUMPEND:
CALL CLOSEFILE
GOOD:
MOV AX,4C00H
INT 21H

FILEBAD:
MOV AX,6
JMP ERROR

OPENFILE:
MOV DX,FNAME
MOV AX,3D00H
INT 21H
JAE INPUTOPEN
JMP FILEBAD
INPUTOPEN:
MOV [HANDLE],AX
RET

CLOSEFILE:
MOV BX,[HANDLE]
MOV AH,3EH
INT 21H
JB FILEBAD
RET

GETNAME:
MOV DX,PROMPT
CALL TEXT
MOV BX,2400H
MOV AL,10
MOV [BX],AL
MOV DX,2400H
MOV AH,10
INT 21H
MOV DX,NEWLINE
CALL TEXT
MOV BX,2401H
MOV AL,[BX]
MOV AH,0
CMP AX,1
JB BADNAME
CMP AX,8
JA BADNAME
MOV CX,AX
MOV SI,2402H
MOV DI,FNAME
NAMELOOP:
LODSB
CMP AL,97
JB NAMEUP
CMP AL,122
JA NAMEUP
SUB AL,32
NAMEUP:
CMP AL,95
JE NAMECHAR
CMP AL,48
JB BADNAME
CMP AL,57
JBE NAMECHAR
CMP AL,65
JB BADNAME
CMP AL,90
JA BADNAME
NAMECHAR:
STOSB
DEC CX
JNE NAMELOOP
MOV [EXTP],DI
MOV SI,ASMEXT
CALL COPYZ
RET
BADNAME:
MOV AX,1
JMP ERROR

NEXTBYTE:
MOV BX,[HANDLE]
MOV CX,1
MOV DX,CHAR
MOV AH,3FH
INT 21H
JAE BYTEOK
MOV AX,6
JMP ERROR
BYTEOK:
RET

COPYZ:
LODSB
STOSB
CMP AL,0
JNE COPYZ
RET

TEXT:
MOV AH,9
INT 21H
RET

NUMBER:
PUSH AX
PUSH BX
PUSH CX
PUSH DX
PUSH SI
MOV CX,AX
MOV SI,DIVISORS
NEXTPLACE:
MOV BX,SI
MOV DX,[BX]
MOV AL,48
SUBTRACT:
