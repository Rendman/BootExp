CLD
CMP SP,0FFFEH
JE I_ENTRY
MOV AX,4C07H
INT 21H
I_ENTRY:
JMP U_MAIN
U_LETTER:
DW 0
U_MAIN:
CALL R_GETC
MOV [U_LETTER],AX
MOV AX,[R_STATUS]
CMP AX,0
JE I0001
JMP U_FAILURE
I0001:
MOV AX,[U_LETTER]
PUSH AX
MOV AX,65535
POP BX
CMP BX,AX
JNE I0002
JMP U_DONE
I0002:
MOV AX,[U_LETTER]
CALL R_PUTC
MOV AX,[R_STATUS]
MOV AH,4CH
INT 21H
U_DONE:
MOV AX,4C00H
INT 21H
U_FAILURE:
MOV AX,1
MOV AH,4CH
INT 21H
R_OK:
MOV DX,0
MOV [R_STATUS],DX
RET
R_ERROR:
MOV DX,1
MOV [R_STATUS],DX
RET
R_FAIL:
MOV AX,0
JMP R_ERROR

R_PUTC:
MOV [R_BYTE],AL
MOV BX,1
MOV CX,1
MOV DX,R_BYTE
MOV AH,40H
INT 21H
JAE R_PUTCOUNT
JMP R_FAIL
R_PUTCOUNT:
CMP AX,1
JE R_PUTGOOD
JMP R_ERROR
R_PUTGOOD:
JMP R_OK

R_GETC:
MOV BX,0
MOV CX,1
MOV DX,R_BYTE
MOV AH,3FH
INT 21H
JAE R_GETCOUNT
MOV AX,65535
JMP R_ERROR
R_GETCOUNT:
CMP AX,0
JNE R_GETBYTE
MOV AX,65535
JMP R_OK
R_GETBYTE:
MOV AL,[R_BYTE]
MOV AH,0
JMP R_OK

R_STATUS:
DW 0

R_BYTE:
DB 0
