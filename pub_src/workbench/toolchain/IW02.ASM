JE NEAR COUNTFULL
INC AX
MOV [INBYTEHI],AX
MOV AX,0
MOV [INBYTES],AX
RET
INPUTLOW:
INC AX
MOV [INBYTES],AX
RET

NUMBER32:
PUSH AX
PUSH BX
PUSH CX
PUSH DX
PUSH SI
MOV [N32LO],AX
MOV [N32HI],DX
MOV SI,DIV32
N32PLACE:
