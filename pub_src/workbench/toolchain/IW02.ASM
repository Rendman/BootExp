START:
CLD
CMP SP,0FFFEH
JNE NEAR MEMORYBAD
CALL OPENFILE
READNEXT:
CALL READLINE
CMP AX,0
JE NEAR READDONE
MOV SI,0C800H
SHOWTOKEN:
CALL SCAN
MOV AX,[TOKLEN]
CMP AX,0
JE NEAR READNEXT
PUSH SI
MOV SI,0CC00H
MOV DL,91
MOV AH,2
INT 21H
TOKENBYTE:
LODSB
CMP AL,0
JE NEAR TOKENEND
MOV DL,AL
MOV AH,2
INT 21H
JMP TOKENBYTE
TOKENEND:
MOV DL,93
MOV AH,2
INT 21H
POP SI
JMP SHOWTOKEN
JMP READNEXT
READDONE:
CALL CLOSEFILE
MOV AX,4C00H
INT 21H
MEMORYBAD:
MOV AX,7
JMP ERROR

FILEBAD:
MOV AX,6
JMP ERROR

OPENFILE:
MOV DX,SRCNAME
MOV AX,3D00H
INT 21H
JAE NEAR INPUTOPEN
JMP FILEBAD
INPUTOPEN:
MOV [HANDLE],AX
MOV AL,1
MOV [INOPEN],AL
RET

CLOSEFILE:
MOV BX,[HANDLE]
MOV AH,3EH
INT 21H
JAE NEAR INPUTCLOSED
JMP FILEBAD
INPUTCLOSED:
MOV AL,0
MOV [INOPEN],AL
RET

NEXTBYTE:
MOV AX,[RDPOS]
MOV DX,[RDLEN]
CMP AX,DX
JB NEAR BUFFERBYTE
MOV BX,[HANDLE]
MOV DX,0D000H
MOV CX,4096
MOV AH,3FH
INT 21H
JAE NEAR REFILLED
JMP FILEBAD
REFILLED:
MOV [RDLEN],AX
MOV DX,0
MOV [RDPOS],DX
CMP AX,0
JE NEAR BUFFEREND
BUFFERBYTE:
MOV BX,[RDPOS]
ADD BX,0D000H
MOV AL,[BX]
MOV [CHAR],AL
MOV AX,[RDPOS]
INC AX
MOV [RDPOS],AX
CALL COUNTINPUT
MOV AX,1
RET
BUFFEREND:
MOV AX,0
RET

READLINE:
MOV DI,0C800H
MOV BP,0
MOV AL,[ENDED]
CMP AL,0
JE NEAR READCHAR
MOV AX,0
RET
READCHAR:
CALL NEXTBYTE
CMP AX,0
JE NEAR ENDFILE
MOV AL,[CHAR]
CMP AL,10
JE NEAR LINEFEED
MOV AH,0
MOV [SKIPLF],AH
CMP AL,13
JE NEAR CARRIAGE
CMP AL,26
JE NEAR ENDFILE
CMP BP,1023
JAE NEAR READFULL
CMP AL,9
JE NEAR KEEPCHAR
CMP AL,32
JB NEAR READBAD
CMP AL,126
JA NEAR READBAD
KEEPCHAR:
STOSB
INC BP
JMP READCHAR
LINEFEED:
MOV AL,[SKIPLF]
CMP AL,0
JE NEAR LINEEND
MOV AL,0
MOV [SKIPLF],AL
JMP READCHAR
CARRIAGE:
MOV AL,1
MOV [SKIPLF],AL
JMP LINEEND
ENDFILE:
MOV AL,1
MOV [ENDED],AL
CMP BP,0
JE NEAR EMPTYEND
LINEEND:
MOV AL,0
STOSB
CALL COUNTLINE
MOV AX,1
RET
EMPTYEND:
MOV AX,0
RET
READFULL:
MOV AX,5
JMP READFAIL
READBAD:
MOV AX,6
READFAIL:
PUSH AX
CALL COUNTLINE
POP AX
JMP ERROR

SCAN:
MOV DI,0CC00H
SCANSPACE:
LODSB
CMP AL,32
JE NEAR SCANSPACE
CMP AL,9
JE NEAR SCANSPACE
CMP AL,0
JE NEAR SCANEND
CMP AL,59
JE NEAR SCANEND
CALL TOKENCHAR
STOSB
CALL SEPARATOR
CMP AH,1
JE NEAR SCANDONE
SCANMORE:
LODSB
CMP AL,0
JE NEAR SCANBACK
CMP AL,32
JE NEAR SCANBACK
CMP AL,9
JE NEAR SCANBACK
CMP AL,59
JE NEAR SCANBACK
CALL SEPARATOR
CMP AH,1
JE NEAR SCANBACK
CMP DI,0CC3FH
JAE NEAR TOKENBAD
CALL TOKENCHAR
STOSB
JMP SCANMORE
SCANBACK:
DEC SI
SCANDONE:
MOV AX,DI
SUB AX,0CC00H
MOV [TOKLEN],AX
MOV AL,0
STOSB
RET
SCANEND:
DEC SI
JMP SCANDONE
TOKENBAD:
MOV AX,1
JMP ERROR
TOKENCHAR:
CMP AL,97
JB NEAR TOKENKEPT
CMP AL,122
JA NEAR TOKENKEPT
SUB AL,32
TOKENKEPT:
RET
SEPARATOR:
