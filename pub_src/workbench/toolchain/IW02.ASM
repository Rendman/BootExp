JE NEAR SEPARATORRET
CMP AL,45
JE NEAR SEPARATORRET
CMP AL,40
JE NEAR SEPARATORRET
CMP AL,41
JE NEAR SEPARATORRET
CMP AL,34
JE NEAR SEPARATORRET
MOV AH,0
SEPARATORRET:
RET

TEXT:
MOV AH,9
INT 21H
RET

ERROR:
MOV [ERRCODE],AL
CALL CLEANUP
MOV DX,ERRMSG
CALL TEXT
MOV AX,[LINENO]
MOV DX,[LINEHI]
CALL NUMBER32
MOV DX,CODEMSG
CALL TEXT
MOV AL,[ERRCODE]
ADD AL,48
MOV DL,AL
MOV AH,2
INT 21H
MOV DX,NEWLINE
CALL TEXT
MOV AL,[CLEANFAIL]
MOV DL,[KEEPFILES]
OR AL,DL
MOV DL,[HAVEBAK]
OR AL,DL
CMP AL,0
JE NEAR ERROREXIT
MOV DX,RECOVERMSG
CALL TEXT
