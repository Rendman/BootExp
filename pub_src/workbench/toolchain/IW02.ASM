MOV AL,[KEEPFILES]
CMP AL,0
JNE NEAR CLEANEND
MOV DX,TMPNAME
MOV AH,41H
INT 21H
JAE NEAR CLEANEND
MOV AL,1
MOV [CLEANFAIL],AL
CLEANEND:
RET

COUNTLINE:
MOV AX,[LINENO]
CMP AX,0FFFFH
JNE NEAR LINELOW
MOV AX,[LINEHI]
CMP AX,0FFFFH
JE NEAR COUNTFULL
INC AX
