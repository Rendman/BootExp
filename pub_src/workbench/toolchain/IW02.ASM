MOV AX,[BX]
MOV [D32HI],AX
ADD BX,2
MOV AX,[BX]
MOV [D32LO],AX
MOV CX,0
N32SUB:
MOV AX,[N32HI]
MOV DX,[D32HI]
CMP AX,DX
JB NEAR N32DIGIT
JA NEAR N32TAKE
MOV AX,[N32LO]
MOV DX,[D32LO]
CMP AX,DX
JB NEAR N32DIGIT
N32TAKE:
MOV AX,[N32LO]
MOV DX,[D32LO]
SUB AX,DX
MOV [N32LO],AX
JAE NEAR N32NOBORROW
MOV AX,[N32HI]
DEC AX
MOV [N32HI],AX
N32NOBORROW:
MOV AX,[N32HI]
MOV DX,[D32HI]
SUB AX,DX
MOV [N32HI],AX
INC CX
JMP N32SUB
N32DIGIT:
MOV DL,CL
ADD DL,48
MOV AH,2
INT 21H
ADD SI,4
CMP SI,DIV32END
JB NEAR N32PLACE
POP SI
POP DX
POP CX
POP BX
POP AX
RET

