; Authored seed routines. Instructions are all accepted by the published ASM86.
; @block START
START:
CLD
CMP SP,0FFFEH
JE ROOM
MOV AX,7
JMP ERROR
ROOM:
CALL PREFLIGHT
MOV AL,1
MOV [PASS],AL
MOV AX,0
MOV [SYMC],AX
MOV AX,5000H
MOV [SYMNEXT],AX
PASSSTART:
MOV AX,100H
MOV [PC],AX
MOV AX,0
MOV [LINENO],AX
MOV [RDPOS],AX
MOV [RDLEN],AX
MOV [OUTCNT],AX
MOV [ENDED],AL
MOV [SKIPLF],AL
MOV AL,[PASS]
CMP AL,2
JNE PASSINPUT
CALL CREATEOUT
PASSINPUT:
CALL OPENFILE
NEXTLINE:
CALL READLINE
CMP AX,0
JE PASSEND
MOV SI,4000H
CALL STATEMENT
JMP NEXTLINE
PASSEND:
CALL CLOSEFILE
MOV AL,[PASS]
CMP AL,1
JNE PASSCHECK
MOV AX,[PC]
MOV [ENDPC],AX
MOV AL,2
MOV [PASS],AL
JMP PASSSTART
PASSCHECK:
MOV AX,[PC]
MOV DX,[ENDPC]
CMP AX,DX
JE PASSVALID
MOV AX,3
JMP ERROR
PASSVALID:
CALL FLUSH
CALL CLOSEOUT
CALL COMMIT
MOV DX,OKMSG
CALL TEXT
MOV AX,[PC]
SUB AX,100H
CALL NUMBER
MOV DX,BYTEMSG
CALL TEXT
GOOD:
MOV AX,4C00H
INT 21H
; @block OPENFILE
OPENFILE:
MOV DX,SRCNAME
MOV AX,3D00H
INT 21H
JAE INPUTOPEN
JMP FILEBAD
INPUTOPEN:
MOV [HANDLE],AX
MOV AL,1
MOV [INOPEN],AL
RET
; @block CLOSEFILE
CLOSEFILE:
MOV BX,[HANDLE]
MOV AH,3EH
INT 21H
JAE INPUTCLOSED
JMP FILEBAD
INPUTCLOSED:
MOV AL,0
MOV [INOPEN],AL
RET
; @block CREATEOUT
CREATEOUT:
MOV DX,TMPNAME
MOV CX,0
MOV AH,3CH
INT 21H
JAE OUTPUTOPEN
JMP FILEBAD
OUTPUTOPEN:
MOV [OUTHANDLE],AX
MOV AL,1
MOV [OUTOPEN],AL
MOV [OWNTMP],AL
RET
CLOSEOUT:
MOV BX,[OUTHANDLE]
MOV AH,3EH
INT 21H
JAE OUTPUTCLOSED
JMP FILEBAD
OUTPUTCLOSED:
MOV AL,0
MOV [OUTOPEN],AL
RET
; @block FLUSH
FLUSH:
PUSH AX
PUSH BX
PUSH CX
PUSH DX
MOV CX,[OUTCNT]
CMP CX,0
JE FLUSHDONE
MOV BX,[OUTHANDLE]
MOV DX,4600H
MOV AH,40H
INT 21H
JAE FLUSHCOUNT
JMP FILEBAD
FLUSHCOUNT:
CMP AX,CX
JE FLUSHGOOD
JMP FILEBAD
FLUSHGOOD:
MOV AX,0
MOV [OUTCNT],AX
FLUSHDONE:
POP DX
POP CX
POP BX
POP AX
RET
; @block NEXTBYTE
NEXTBYTE:
MOV AX,[RDPOS]
MOV DX,[RDLEN]
CMP AX,DX
JB BUFFERBYTE
MOV BX,[HANDLE]
MOV DX,4200H
MOV CX,1024
MOV AH,3FH
INT 21H
JAE REFILLED
JMP FILEBAD
REFILLED:
MOV [RDLEN],AX
MOV DX,0
MOV [RDPOS],DX
CMP AX,0
JE BUFFEREND
BUFFERBYTE:
MOV BX,[RDPOS]
ADD BX,4200H
MOV AL,[BX]
MOV [CHAR],AL
MOV AX,[RDPOS]
INC AX
MOV [RDPOS],AX
MOV AX,1
RET
BUFFEREND:
MOV AX,0
RET
; @block EMIT
EMIT:
PUSH AX
PUSH BX
MOV BX,[PC]
CMP BX,0F000H
JB EMITROOM
MOV AX,5
JMP ERROR
EMITROOM:
MOV AH,[PASS]
CMP AH,2
JNE COUNTBYTE
MOV BX,[OUTCNT]
ADD BX,4600H
MOV [BX],AL
MOV BX,[OUTCNT]
INC BX
MOV [OUTCNT],BX
CMP BX,1024
JB COUNTBYTE
CALL FLUSH
COUNTBYTE:
MOV BX,[PC]
INC BX
MOV [PC],BX
POP BX
POP AX
RET
; @block EXISTS
EXISTS:
MOV AX,3D00H
INT 21H
JAE FILEEXISTS
CMP AX,2
JE FILENONE
JMP FILEBAD
FILEEXISTS:
MOV BX,AX
MOV AH,3EH
INT 21H
JAE EXISTSCLOSED
JMP FILEBAD
EXISTSCLOSED:
MOV AX,1
RET
FILENONE:
MOV AX,0
RET
PREFLIGHT:
MOV DX,TMPNAME
CALL EXISTS
CMP AX,0
JNE NAMEBUSY
MOV DX,BAKNAME
CALL EXISTS
CMP AX,0
JE PREFLIGHTOK
NAMEBUSY:
MOV AX,8
JMP ERROR
PREFLIGHTOK:
RET
; @block COMMIT
COMMIT:
MOV DX,RESNAME
CALL EXISTS
CMP AX,0
JE PUBLISH
MOV DX,RESNAME
MOV DI,BAKNAME
MOV AH,56H
INT 21H
JAE BACKEDUP
JMP FILEBAD
BACKEDUP:
MOV AL,1
MOV [HAVEBAK],AL
PUBLISH:
MOV DX,TMPNAME
MOV DI,RESNAME
MOV AH,56H
INT 21H
JAE PUBLISHED
MOV AL,[HAVEBAK]
CMP AL,0
JE PUBLISHFAIL
MOV DX,BAKNAME
MOV DI,RESNAME
MOV AH,56H
INT 21H
JAE RESTORED
MOV AL,1
MOV [KEEPFILES],AL
JMP PUBLISHFAIL
RESTORED:
MOV AL,0
MOV [HAVEBAK],AL
PUBLISHFAIL:
JMP FILEBAD
PUBLISHED:
MOV AL,0
MOV [OWNTMP],AL
MOV AL,[HAVEBAK]
CMP AL,0
JE COMMITDONE
MOV DX,BAKNAME
MOV AH,41H
INT 21H
JAE BACKREMOVED
JMP FILEBAD
BACKREMOVED:
MOV AL,0
MOV [HAVEBAK],AL
COMMITDONE:
RET
; @block CLEANUP
CLEANUP:
MOV AL,[INOPEN]
CMP AL,0
JE CLEANOUTPUT
MOV BX,[HANDLE]
MOV AH,3EH
INT 21H
JAE CLEANOUTPUT
MOV AL,1
MOV [CLEANFAIL],AL
CLEANOUTPUT:
MOV AL,[OUTOPEN]
CMP AL,0
JE CLEANTEMP
MOV BX,[OUTHANDLE]
MOV AH,3EH
INT 21H
JAE CLEANTEMP
MOV AL,1
MOV [CLEANFAIL],AL
CLEANTEMP:
MOV AL,[OWNTMP]
CMP AL,0
JE CLEANEND
MOV AL,[KEEPFILES]
CMP AL,0
JNE CLEANEND
MOV DX,TMPNAME
MOV AH,41H
INT 21H
JAE CLEANEND
MOV AL,1
MOV [CLEANFAIL],AL
CLEANEND:
RET
; @block ERROR
ERROR:
MOV [ERRCODE],AL
CALL CLEANUP
MOV DX,ERRMSG
CALL TEXT
MOV AX,[LINENO]
CALL NUMBER
MOV DX,CODEMSG
CALL TEXT
MOV AL,[ERRCODE]
ADD AL,48
MOV DL,AL
MOV AH,2
INT 21H
MOV DX,NEWLINE
CALL TEXT
MOV AL,[CLEANFAIL]
MOV DL,[KEEPFILES]
OR AL,DL
MOV DL,[HAVEBAK]
OR AL,DL
CMP AL,0
JE ERROREXIT
MOV DX,RECOVERMSG
CALL TEXT
ERROREXIT:
MOV AX,4C01H
INT 21H
; @block SEGOPERAND
SEGOPERAND:
MOV [SEGCODE],AX
PUSH SI
CALL SCAN
MOV AL,[4080H]
CMP AL,58
JNE SEGREGISTER
POP AX
MOV AX,[SEGCODE]
CMP AX,16
JE SEGES
JMP TWOBAD
SEGES:
CALL SCAN
MOV AL,[4080H]
CMP AL,91
JE SEGMEMORY
JMP TWOBAD
SEGMEMORY:
CALL MEMORY
MOV AL,38
MOV [PREFIX],AL
RET
SEGREGISTER:
POP SI
MOV AX,[SEGCODE]
SUB AX,16
MOV [REG],AL
MOV AL,1
MOV [WIDTH],AL
MOV AL,4
MOV [KIND],AL
RET
; @block SEGMOV
SEGMOV:
MOV AL,[K1]
CMP AL,4
JNE SEGLOAD
MOV AL,[R1]
CMP AL,1
JE SEGBAD
MOV AL,[KIND]
CMP AL,1
JNE SEGBAD
MOV AL,[WIDTH]
CMP AL,1
JNE SEGBAD
MOV AL,142
CALL EMIT
MOV AL,[R1]
CALL TIMES8
MOV DL,[REG]
JMP SEGMOD
SEGLOAD:
MOV AL,[K1]
CMP AL,1
JNE SEGBAD
MOV AL,[W1]
CMP AL,1
JNE SEGBAD
MOV AL,140
CALL EMIT
MOV AL,[REG]
CALL TIMES8
MOV DL,[R1]
SEGMOD:
ADD AL,DL
ADD AL,192
CALL EMIT
RET
SEGBAD:
JMP TWOBAD
