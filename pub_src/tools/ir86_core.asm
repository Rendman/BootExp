; @block EMITCHAR
EMITCHAR:
PUSH BX
MOV BX,[OUTPTR]
CMP BX,0E000H
JB CHARROOM
JMP TEXTFULL
CHARROOM:
MOV [BX],AL
INC BX
MOV [OUTPTR],BX
CMP AL,10
JNE CHARDONE
MOV BX,[OUTLINES]
INC BX
CMP BX,4000
JBE LINEROOM
JMP TEXTFULL
LINEROOM:
MOV [OUTLINES],BX
CHARDONE:
POP BX
RET
TEXTFULL:
MOV AX,5
JMP ERROR
; @block OUTTEXT
OUTTEXT:
LODSB
CMP AL,0
JE OUTDONE
CALL EMITCHAR
JMP OUTTEXT
OUTDONE:
RET
; @block EXPAND
EXPAND:
LODSB
CMP AL,0
JE EXPANDDONE
CMP AL,64
JE EXPANDNAME
CMP AL,35
JE EXPANDNUMBER
CMP AL,63
JE EXPANDBRANCH
CALL EMITCHAR
JMP EXPAND
EXPANDNAME:
PUSH SI
MOV SI,2500H
CALL OUTTEXT
POP SI
JMP EXPAND
EXPANDNUMBER:
PUSH SI
MOV SI,2520H
CALL OUTTEXT
POP SI
JMP EXPAND
EXPANDBRANCH:
MOV AX,[BRANCHNO]
CALL FOUR
JMP EXPAND
EXPANDDONE:
RET
; @block FOUR
FOUR:
PUSH AX
PUSH BX
PUSH CX
PUSH DX
PUSH SI
MOV CX,AX
MOV SI,FOURDIV
FOURPLACE:
MOV BX,SI
MOV DX,[BX]
MOV AL,48
FOURSUB:
CMP CX,DX
JB FOURDIGIT
SUB CX,DX
ADD AL,1
JMP FOURSUB
FOURDIGIT:
CALL EMITCHAR
ADD SI,2
CMP SI,FOUREND
JB FOURPLACE
POP SI
POP DX
POP CX
POP BX
POP AX
RET
