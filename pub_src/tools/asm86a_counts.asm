; @block COUNTLINE
COUNTLINE:
MOV AX,[LINENO]
CMP AX,0FFFFH
JNE LINELOW
MOV AX,[LINEHI]
CMP AX,0FFFFH
JE COUNTFULL
INC AX
MOV [LINEHI],AX
MOV AX,0
MOV [LINENO],AX
RET
LINELOW:
INC AX
MOV [LINENO],AX
RET
COUNTFULL:
MOV AX,5
JMP ERROR
; @block COUNTINPUT
COUNTINPUT:
MOV AX,[INBYTES]
CMP AX,0FFFFH
JNE INPUTLOW
MOV AX,[INBYTEHI]
CMP AX,0FFFFH
JE COUNTFULL
INC AX
MOV [INBYTEHI],AX
MOV AX,0
MOV [INBYTES],AX
RET
INPUTLOW:
INC AX
MOV [INBYTES],AX
RET
; @block NUMBER32
NUMBER32:
PUSH AX
PUSH BX
PUSH CX
PUSH DX
PUSH SI
MOV [N32LO],AX
MOV [N32HI],DX
MOV SI,DIV32
N32PLACE:
MOV BX,SI
MOV AX,[BX]
MOV [D32HI],AX
ADD BX,2
MOV AX,[BX]
MOV [D32LO],AX
MOV CX,0
N32SUB:
MOV AX,[N32HI]
MOV DX,[D32HI]
CMP AX,DX
JB N32DIGIT
JA N32TAKE
MOV AX,[N32LO]
MOV DX,[D32LO]
CMP AX,DX
JB N32DIGIT
N32TAKE:
MOV AX,[N32LO]
MOV DX,[D32LO]
SUB AX,DX
MOV [N32LO],AX
JAE N32NOBORROW
MOV AX,[N32HI]
DEC AX
MOV [N32HI],AX
N32NOBORROW:
MOV AX,[N32HI]
MOV DX,[D32HI]
SUB AX,DX
MOV [N32HI],AX
INC CX
JMP N32SUB
N32DIGIT:
MOV DL,CL
ADD DL,48
MOV AH,2
INT 21H
ADD SI,4
CMP SI,DIV32END
JB N32PLACE
POP SI
POP DX
POP CX
POP BX
POP AX
RET
