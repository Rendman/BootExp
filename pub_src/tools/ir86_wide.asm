; @block START
START:
CLD
CMP SP,0FFFEH
JNE NEAR MEMORYBAD
CALL PREFLIGHT
CALL OPENFILE
CALL CREATEOUT
MOV SI,T_HEADER
CALL OUTTEXT
IRLINE:
CALL READLINE
CMP AX,0
JE NEAR IRDONE
MOV SI,0C800H
CALL STATEMENT
JMP IRLINE
IRDONE:
CALL BALANCED
CALL CLOSEFILE
MOV SI,T_RUNTIME
CALL OUTTEXT
CALL FLUSH
CALL CLOSEOUT
CALL COMMIT
MOV DX,OKMSG
CALL TEXT
MOV AX,[TOTALLO]
MOV DX,[TOTALHI]
CALL NUMBER32
MOV DX,BYTEMSG
CALL TEXT
MOV AX,4C00H
INT 21H
MEMORYBAD:
MOV AX,7
JMP ERROR
; @block EMITCHAR
EMITCHAR:
PUSH BX
MOV BX,[OUTCNT]
ADD BX,0E000H
MOV [BX],AL
MOV BX,[TOTALLO]
INC BX
MOV [TOTALLO],BX
CMP BX,0
JNE COUNTGOOD
MOV BX,[TOTALHI]
INC BX
MOV [TOTALHI],BX
CMP BX,0
JE NEAR TABLEFULL
COUNTGOOD:
MOV BX,[OUTCNT]
INC BX
MOV [OUTCNT],BX
CMP BX,4096
JNE CHARDONE
CALL FLUSH
CHARDONE:
POP BX
RET
; @block OUTTEXT
OUTTEXT:
LODSB
CMP AL,0
JE OUTDONE
CALL EMITCHAR
JMP OUTTEXT
OUTDONE:
RET
; @block OUTNUM
OUTNUM:
PUSH AX
PUSH BX
PUSH CX
PUSH DX
PUSH SI
MOV CX,AX
MOV SI,DIVISORS
OUTPLACE:
MOV BX,SI
MOV DX,[BX]
MOV AL,48
OUTSUB:
CMP CX,DX
JB OUTDIGIT
SUB CX,DX
ADD AL,1
JMP OUTSUB
OUTDIGIT:
CALL EMITCHAR
ADD SI,2
CMP SI,DIVEND
JB OUTPLACE
POP SI
POP DX
POP CX
POP BX
POP AX
RET
; @block EXPAND
EXPAND:
LODSB
CMP AL,0
JE EXPANDDONE
CMP AL,64
JE EXPANDNAME
CMP AL,35
JE EXPANDNUM
CMP AL,63
JE EXPANDID
CALL EMITCHAR
JMP EXPAND
EXPANDNAME:
PUSH SI
MOV SI,IRNAME
CALL OUTTEXT
POP SI
JMP EXPAND
EXPANDNUM:
MOV AX,[NUMV]
CALL OUTNUM
JMP EXPAND
EXPANDID:
MOV AX,[STRID]
CALL OUTNUM
JMP EXPAND
EXPANDDONE:
RET
; @block NUMARG
NUMARG:
CALL SCAN
CALL ATOM
MOV [NUMV],AX
RET
; @block NAMEARG
NAMEARG:
CALL SCAN
MOV AX,[TOKLEN]
CMP AX,29
JA NEAR SYMBOLBAD
CALL VALIDNAME
PUSH SI
MOV SI,0CC00H
MOV DI,IRNAME
CALL COPYZ
POP SI
RET
; @block STATEMENT
STATEMENT:
CALL SCAN
MOV AL,[0CC00H]
CMP AL,0
JE STATDONE
MOV BX,IRTAB
MOV CX,OPCOUNT
MOV AX,14
CALL LOOK
CMP BX,0
JE NEAR SYNTAXBAD
ADD BX,8
MOV AL,[BX]
MOV [IRCLASS],AL
INC BX
MOV AL,[BX]
MOV [IRDELTA],AL
ADD BX,3
MOV AX,[BX]
MOV [TPL],AX
MOV AL,[IRCLASS]
CMP AL,1
JE STATNUMBER
CMP AL,2
JE STATNAME
CMP AL,3
JE STATDATA
CMP AL,4
JE STATPROC
CMP AL,5
JE STATINVOKE
CMP AL,6
JE STATSTRING
JMP STATFINISH
STATNUMBER:
CALL NUMARG
JMP STATFINISH
STATNAME:
CALL NAMEARG
JMP STATFINISH
STATDATA:
CALL NAMEARG
CALL NUMARG
JMP STATFINISH
STATPROC:
CALL BALANCED
CALL NAMEARG
CALL NUMARG
CMP AX,16
JA NEAR SYNTAXBAD
MOV [PARAMS],AX
CALL NUMARG
CMP AX,64
JA NEAR SYNTAXBAD
MOV [LOCALS],AX
ADD AX,AX
MOV [NUMV],AX
JMP STATFINISH
STATINVOKE:
CALL NAMEARG
CALL NUMARG
MOV DX,[DEPTH]
CMP DX,AX
JB NEAR STACKBAD
SUB DX,AX
MOV [DEPTH],DX
ADD AX,AX
MOV [NUMV],AX
JMP STATFINISH
STATSTRING:
CALL STRINGOUT
RET
STATFINISH:
CALL FINISH
MOV AL,[IRCLASS]
CMP AL,2
JNE STATLOCAL
MOV AX,[TPL]
CMP AX,T_LABEL
JNE STATLOCAL
CALL BALANCED
STATLOCAL:
MOV AX,[TPL]
CMP AX,T_LOCAL
JE LOCALOFFSET
CMP AX,T_SETLOCAL
JE LOCALOFFSET
CMP AX,T_LADDR
JE LOCALOFFSET
CMP AX,T_PARAM
JE PARAMOFFSET
CMP AX,T_SETPARAM
JE PARAMOFFSET
CMP AX,T_PADDR
JE PARAMOFFSET
JMP STATFLOW
LOCALOFFSET:
MOV AX,[NUMV]
CMP AX,[LOCALS]
JAE NEAR SYNTAXBAD
INC AX
ADD AX,AX
MOV [NUMV],AX
JMP STATFLOW
PARAMOFFSET:
MOV AX,[PARAMS]
MOV DX,[NUMV]
CMP DX,AX
JAE NEAR SYNTAXBAD
SUB AX,DX
ADD AX,AX
ADD AX,2
MOV [NUMV],AX
STATFLOW:
MOV AL,[IRDELTA]
CMP AL,1
JE FLOWPUSH
CMP AL,2
JE FLOWPOP
CMP AL,3
JE FLOWTWO
CMP AL,4
JE FLOWBOUND
JMP STATEXPAND
FLOWPUSH:
MOV AX,[DEPTH]
CMP AX,256
JAE NEAR TABLEFULL
INC AX
MOV [DEPTH],AX
JMP STATEXPAND
FLOWTWO:
MOV AX,[DEPTH]
CMP AX,2
JB NEAR STACKBAD
SUB AX,2
MOV [DEPTH],AX
JMP STATEXPAND
FLOWPOP:
MOV AX,[DEPTH]
CMP AX,0
JE NEAR STACKBAD
DEC AX
MOV [DEPTH],AX
MOV AL,[IRCLASS]
CMP AL,2
JNE FLOWPOPDONE
CALL BALANCED
FLOWPOPDONE:
JMP STATEXPAND
FLOWBOUND:
CALL BALANCED
STATEXPAND:
MOV SI,[TPL]
CALL EXPAND
STATDONE:
RET
; @block BALANCED
BALANCED:
MOV AX,[DEPTH]
CMP AX,0
JNE NEAR STACKBAD
RET
STACKBAD:
MOV AX,4
JMP ERROR
SYNTAXBAD:
MOV AX,1
JMP ERROR
TABLEFULL:
MOV AX,5
JMP ERROR
; @block STRINGOUT
STRINGOUT:
MOV AX,[STRID]
INC AX
CMP AX,0
JE NEAR TABLEFULL
MOV [STRID],AX
PUSH SI
MOV SI,T_LITS
CALL EXPAND
POP SI
STRINGSPACE:
LODSB
CMP AL,32
JE STRINGSPACE
CMP AL,9
JE STRINGSPACE
CMP AL,34
JNE NEAR SYNTAXBAD
STRINGCHAR:
LODSB
CMP AL,0
JE NEAR SYNTAXBAD
CMP AL,34
JE STRINGEND
CMP AL,92
JNE STRINGBYTE
LODSB
CMP AL,110
JNE NOTLF
MOV AL,10
JMP STRINGBYTE
NOTLF:
CMP AL,114
JNE NOTCR
MOV AL,13
JMP STRINGBYTE
NOTCR:
CMP AL,116
JNE NOTTAB
MOV AL,9
JMP STRINGBYTE
NOTTAB:
CMP AL,48
JNE NOTZERO
MOV AL,0
JMP STRINGBYTE
NOTZERO:
CMP AL,92
JE STRINGBYTE
CMP AL,34
JNE NEAR SYNTAXBAD
STRINGBYTE:
MOV AH,0
CALL OUTNUM
PUSH SI
MOV SI,T_STRINGNEXT
CALL OUTTEXT
POP SI
JMP STRINGCHAR
STRINGEND:
CALL FINISH
MOV SI,T_LITSEND
CALL EXPAND
RET
