; ASM86: an assembler written in BOOTASM's assembly language.
START:
CLD
CMP SP,0FFFEH
JE ROOM
MOV AX,7
JMP ERROR
ROOM:
MOV AL,1
MOV [PASS],AL
MOV AX,0
MOV [SYMC],AX
MOV AX,3000H
MOV [SYMNEXT],AX
PASSSTART:
MOV AX,100H
MOV [PC],AX
MOV AX,6000H
MOV [OUTPTR],AX
MOV AX,0
MOV [LINENO],AX
MOV [ENDED],AL
MOV [SKIPLF],AL
CALL OPENFILE
NEXTLINE:
CALL READLINE
CMP AX,0
JE PASSEND
MOV SI,2200H
CALL STATEMENT
JMP NEXTLINE
PASSEND:
CALL CLOSEFILE
MOV AL,[PASS]
ADD AL,1
MOV [PASS],AL
CMP AL,3
JB PASSSTART
CALL WRITEOUT
GOOD:
MOV AX,4C00H
INT 21H
FILEBAD:
MOV AX,6
JMP ERROR

OPENFILE:
MOV DX,FNAME
MOV AX,3D00H
INT 21H
JAE INPUTOPEN
JMP FILEBAD
INPUTOPEN:
MOV [HANDLE],AX
RET
CLOSEFILE:
MOV BX,[HANDLE]
MOV AH,3EH
INT 21H
JB FILEBAD
RET
WRITEOUT:
MOV DX,RESNAME
MOV CX,0
MOV AH,3CH
INT 21H
JB FILEBAD
MOV [HANDLE],AX
MOV BX,AX
MOV CX,[PC]
SUB CX,100H
MOV DX,6000H
MOV AH,40H
INT 21H
JB FILEBAD
CMP AX,CX
JNE FILEBAD
MOV BX,[HANDLE]
MOV AH,3EH
INT 21H
JB FILEBAD
MOV DX,OKMSG
CALL TEXT
MOV AX,[PC]
SUB AX,100H
CALL NUMBER
MOV DX,BYTEMSG
CALL TEXT
RET
NEXTBYTE:
MOV BX,[HANDLE]
MOV CX,1
MOV DX,CHAR
MOV AH,3FH
INT 21H
JAE BYTEOK
MOV AX,6
JMP ERROR
BYTEOK:
RET

; One bounded physical source line; AX=1 for a line, 0 at EOF.
READLINE:
MOV DI,2200H
MOV BP,0
MOV AL,[ENDED]
CMP AL,0
JE READCHAR
MOV AX,0
RET
READCHAR:
CALL NEXTBYTE
CMP AX,0
JE ENDFILE
MOV AL,[CHAR]
CMP AL,10
JE LINEFEED
MOV AH,0
MOV [SKIPLF],AH
CMP AL,13
JE CARRIAGE
CMP AL,26
JE ENDFILE
CMP BP,120
JAE READFULL
CMP AL,9
JE TABCHAR
CMP AL,32
JB READBAD
CMP AL,126
JA READBAD
CMP AL,97
JB KEEPCHAR
CMP AL,122
JA KEEPCHAR
SUB AL,32
JMP KEEPCHAR
TABCHAR:
MOV AL,32
KEEPCHAR:
STOSB
INC BP
JMP READCHAR
LINEFEED:
MOV AL,[SKIPLF]
CMP AL,0
JE LINEEND
MOV AL,0
MOV [SKIPLF],AL
JMP READCHAR
CARRIAGE:
MOV AL,1
MOV [SKIPLF],AL
JMP LINEEND
ENDFILE:
MOV AL,1
MOV [ENDED],AL
CMP BP,0
JE EMPTYEND
LINEEND:
MOV AL,0
STOSB
MOV AX,[LINENO]
INC AX
CMP AX,4000
JA READFULL
MOV [LINENO],AX
MOV AX,1
RET
EMPTYEND:
MOV AX,0
RET
READFULL:
MOV AX,5
JMP READFAIL
READBAD:
MOV AX,6
READFAIL:
MOV DX,[LINENO]
INC DX
MOV [LINENO],DX
JMP ERROR

; A token is at 2300H; SI points just beyond it in the line.
SCAN:
MOV DI,2300H
SCANSPACE:
LODSB
CMP AL,32
JE SCANSPACE
CMP AL,0
JE SCANEND
CMP AL,59
JE SCANEND
STOSB
CMP AL,44
JE SCANDONE
CMP AL,58
JE SCANDONE
CMP AL,91
JE SCANDONE
CMP AL,93
JE SCANDONE
SCANMORE:
LODSB
CMP AL,0
JE SCANBACK
CMP AL,32
JE SCANBACK
CMP AL,59
JE SCANBACK
CMP AL,44
JE SCANBACK
CMP AL,58
JE SCANBACK
CMP AL,91
JE SCANBACK
CMP AL,93
JE SCANBACK
CMP DI,2310H
JAE TOKENBAD
STOSB
JMP SCANMORE
SCANBACK:
DEC SI
SCANDONE:
MOV AX,DI
SUB AX,2300H
MOV [TOKLEN],AX
MOV AL,0
STOSB
RET
SCANEND:
DEC SI
JMP SCANDONE
TOKENBAD:
MOV AX,1
JMP ERROR

; Search a fixed-record table: BX=base, CX=count, AX=stride.
; Return BX=matching record or zero. Preserve the source cursor SI.
LOOK:
MOV [STRIDE],AX
PUSH SI
MOV BP,BX
LOOKNEXT:
CMP CX,0
JE LOOKMISS
MOV DI,BP
MOV SI,2300H
LOOKCHAR:
LODSB
MOV BX,DI
MOV DL,[BX]
CMP AL,DL
JNE LOOKSTEP
CMP AL,0
JE LOOKFOUND
INC DI
JMP LOOKCHAR
LOOKSTEP:
MOV AX,[STRIDE]
ADD BP,AX
DEC CX
JMP LOOKNEXT
LOOKFOUND:
MOV BX,BP
POP SI
RET
LOOKMISS:
MOV BX,0
POP SI
RET

; Return register encoding 0..15 in AX, or FFFFH if not a register.
REGISTER:
MOV BX,REGTAB
MOV CX,16
MOV AX,4
CALL LOOK
CMP BX,0
JE NOREGISTER
ADD BX,3
MOV AL,[BX]
MOV AH,0
RET
NOREGISTER:
MOV AX,0FFFFH
RET

; Validate a label's letters and digits; preserve source cursor SI.
VALIDNAME:
PUSH SI
MOV SI,2300H
LODSB
CMP AL,95
JE NAMEVALID
CMP AL,65
JB SYMBOLBAD
CMP AL,90
JA SYMBOLBAD
NAMEVALID:
LODSB
CMP AL,0
JE NAMEVALIDEND
CMP AL,95
JE NAMEVALID
CMP AL,48
JB SYMBOLBAD
CMP AL,57
JBE NAMEVALID
CMP AL,65
JB SYMBOLBAD
CMP AL,90
JBE NAMEVALID
JMP SYMBOLBAD
NAMEVALIDEND:
POP SI
RET
SYMBOLBAD:
MOV AX,3
JMP ERROR

; Read a numeric token or symbol, returning an unsigned word in AX.
VALUE:
MOV AL,[2300H]
CMP AL,48
JB WORDVALUE
CMP AL,57
JBE LITERAL
WORDVALUE:
JMP SYMBOLVALUE
LITERAL:
PUSH SI
MOV SI,2300H
MOV DI,[TOKLEN]
ADD DI,2300H
MOV BX,DI
DEC BX
MOV AL,[BX]
MOV BP,10
CMP AL,72
JNE NUMBERSTART
MOV BP,16
DEC DI
NUMBERSTART:
CMP SI,DI
JE NUMBERBAD
MOV CX,0
DIGIT:
LODSB
SUB AL,48
CMP AL,9
JBE DIGITOK
SUB AL,7
CMP AL,10
JB NUMBERBAD
CMP AL,15
JA NUMBERBAD
DIGITOK:
MOV AH,0
MOV DX,AX
CMP DX,BP
JAE NUMBERBAD
CMP BP,16
JE HEXDIGIT
CMP CX,6553
JA NUMBERBAD
JB DECDIGIT
CMP DX,5
JA NUMBERBAD
DECDIGIT:
MOV AX,CX
ADD CX,CX
ADD AX,AX
ADD AX,AX
ADD AX,AX
ADD CX,AX
JMP ADDDIGIT
HEXDIGIT:
CMP CX,4095
JA NUMBERBAD
ADD CX,CX
ADD CX,CX
ADD CX,CX
ADD CX,CX
ADDDIGIT:
ADD CX,DX
CMP SI,DI
JB DIGIT
MOV AX,CX
POP SI
RET
NUMBERBAD:
MOV AX,2
JMP ERROR
SYMBOLVALUE:
CALL VALIDNAME
CALL REGISTER
CMP AX,0FFFFH
JNE VALUEBAD
MOV BX,3000H
MOV CX,[SYMC]
MOV AX,20
CALL LOOK
CMP BX,0
JE NOTDEFINED
ADD BX,18
MOV AX,[BX]
RET
NOTDEFINED:
MOV AL,[PASS]
CMP AL,1
JNE VALUEBAD
MOV AX,0
RET

VALUEBAD:
MOV AX,3
JMP ERROR

; Enter the token as a definition, or check its second-pass address.
DEFINE:
CALL VALIDNAME
CALL REGISTER
CMP AX,0FFFFH
JNE DEFINEBAD
MOV BX,3000H
MOV CX,[SYMC]
MOV AX,20
CALL LOOK
MOV AL,[PASS]
CMP AL,1
JNE CHECKDEFINE
CMP BX,0
JNE DEFINEBAD
MOV AX,[SYMC]
CMP AX,256
JAE TABLEFULL
MOV DI,[SYMNEXT]
PUSH SI
MOV SI,2300H
CALL COPYZ
POP SI
MOV BX,[SYMNEXT]
ADD BX,18
MOV AX,[PC]
MOV [BX],AX
MOV AX,[SYMNEXT]
ADD AX,20
MOV [SYMNEXT],AX
MOV AX,[SYMC]
INC AX
MOV [SYMC],AX
RET
CHECKDEFINE:
CMP BX,0
JE DEFINEBAD
ADD BX,18
MOV AX,[BX]
MOV DX,[PC]
CMP AX,DX
JE DEFINEEND
JMP DEFINEBAD
DEFINEEND:
RET
TABLEFULL:
MOV AX,5
JMP ERROR

DEFINEBAD:
MOV AX,3
JMP ERROR

; Operand result: KIND=1 register, 2 memory, 3 immediate.
OPERAND:
CALL SCAN
MOV AL,[2300H]
CMP AL,91
JE MEMORY
CALL REGISTER
CMP AX,0FFFFH
JE IMMEDIATE
MOV DL,AL
AND AL,7
MOV [REG],AL
MOV AL,0
CMP DL,8
JB REGWIDTH
MOV AL,1
REGWIDTH:
MOV [WIDTH],AL
MOV AL,1
MOV [KIND],AL
RET
IMMEDIATE:
CALL VALUE
MOV [VAL],AX
MOV AL,3
MOV [KIND],AL
RET
MEMORY:
CALL SCAN
MOV AX,[2300H]
CMP AX,5842H
JNE DIRECTMEM
MOV AL,[2302H]
CMP AL,0
JNE DIRECTMEM
MOV AL,7
MOV [REG],AL
JMP MEMORYEND
DIRECTMEM:
CALL VALUE
MOV [VAL],AX
MOV AL,6
MOV [REG],AL
MEMORYEND:
CALL SCAN
MOV AL,[2300H]
CMP AL,93
JE MEMORYOK
MOV AX,1
JMP ERROR
MEMORYOK:
MOV AL,2
MOV [KIND],AL
RET

; A complete line, including a possible standalone label.
STATEMENT:
CALL SCAN
MOV AL,[2300H]
CMP AL,0
JNE AFTERWORD
RET
AFTERWORD:
LODSB
CMP AL,32
JE AFTERWORD
CMP AL,58
JNE INSTRUCTION
CALL DEFINE
CALL FINISH
RET
INSTRUCTION:
DEC SI
MOV BX,OPTAB
MOV CX,31
MOV AX,8
CALL LOOK
CMP BX,0
JE SYNTAXBAD
ADD BX,6
MOV AL,[BX]
MOV [TYPE],AL
INC BX
MOV AL,[BX]
MOV [OP],AL
MOV AL,[TYPE]
CMP AL,1
JNE TYPEFIXED
CALL DATAITEM
RET
TYPEFIXED:
CMP AL,2
JNE TYPESINGLE
CALL FIXED
RET
TYPESINGLE:
CMP AL,5
JNE TYPEINT
CALL SINGLE
RET
TYPEINT:
CMP AL,6
JNE TYPENEAR
CALL INTERRUPT
RET
TYPENEAR:
CMP AL,7
JNE TYPESHORT
CALL NEARJUMP
RET
TYPESHORT:
CMP AL,8
JNE TYPETWO
CALL SHORTJUMP
RET
TYPETWO:
CALL TWOOPERANDS
CALL FINISH
RET
SYNTAXBAD:
MOV AX,1
JMP ERROR

DATAITEM:
CALL SCAN
CALL VALUE
MOV DL,[OP]
CMP DL,0
JE DATABYTE
CALL EMITWORD
JMP DATASEP
DATABYTE:
CALL BYTEVALUE
DATASEP:
CALL SCAN
MOV AL,[2300H]
CMP AL,44
JE DATAITEM
CMP AL,0
JNE SYNTAXBAD
RET
FIXED:
MOV AL,[OP]
CALL EMIT
CALL FINISH
RET
SINGLE:
CALL SCAN
CALL REGISTER
CMP AX,8
JB SYNTAXBAD
CMP AX,15
JA SYNTAXBAD
SUB AL,8
MOV DL,[OP]
ADD AL,DL
CALL EMIT
CALL FINISH
RET
INTERRUPT:
CALL SCAN
CALL VALUE
PUSH AX
MOV AL,205
CALL EMIT
POP AX
CALL BYTEVALUE
CALL FINISH
RET
NEARJUMP:
CALL SCAN
CALL VALUE
MOV DX,[PC]
ADD DX,3
SUB AX,DX
PUSH AX
MOV AL,[OP]
CALL EMIT
POP AX
CALL EMITWORD
CALL FINISH
RET
SHORTJUMP:
CALL SCAN
CALL VALUE
MOV DX,[PC]
ADD DX,2
SUB AX,DX
MOV DL,[PASS]
CMP DL,1
JE SHORTOK
CMP AX,127
JBE SHORTOK
CMP AX,0FF80H
JAE SHORTOK
MOV AX,4
JMP ERROR
SHORTOK:
PUSH AX
MOV AL,[OP]
CALL EMIT
POP AX
CALL EMIT
CALL FINISH
RET
FINISH:
CALL SCAN
MOV AL,[2300H]
CMP AL,0
JE FINISHED
MOV AX,1
JMP ERROR
FINISHED:
RET

; Retain the first operand while scanning the second.
TWOOPERANDS:
CALL OPERAND
MOV AL,[KIND]
MOV [K1],AL
MOV AL,[WIDTH]
MOV [W1],AL
MOV AL,[REG]
MOV [R1],AL
MOV AX,[VAL]
MOV [V1],AX
CALL SCAN
