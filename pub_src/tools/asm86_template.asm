CMP AL,3
JE MOVOPERANDS
MOV AL,[K1]
CMP AL,1
JNE TWOBAD
MOV AL,[KIND]
CMP AL,1
JE MATHREG
CMP AL,3
JNE TWOBAD
MOV AL,[W1]
ADD AL,128
CALL EMIT
MOV AL,[OP]
CALL TIMES8
MOV DL,[R1]
