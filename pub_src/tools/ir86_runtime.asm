; Authored 8086/DOS binding for the processor-neutral IR86 runtime API.
; @part STATUS
R_STATUS:
DW 0
; @part RESULT
R_OK:
MOV DX,0
MOV [R_STATUS],DX
RET
R_ERROR:
MOV DX,1
MOV [R_STATUS],DX
RET
R_FAIL:
MOV AX,0
JMP R_ERROR
; @part PUTC
R_PUTC:
MOV [R_BYTE],AL
MOV BX,1
MOV CX,1
MOV DX,R_BYTE
MOV AH,40H
INT 21H
JAE R_PUTCOUNT
JMP R_FAIL
R_PUTCOUNT:
CMP AX,1
JE R_PUTGOOD
JMP R_ERROR
R_PUTGOOD:
JMP R_OK
; @part GETC
R_GETC:
MOV BX,0
MOV CX,1
MOV DX,R_BYTE
MOV AH,3FH
INT 21H
JAE R_GETCOUNT
MOV AX,65535
JMP R_ERROR
R_GETCOUNT:
CMP AX,0
JNE R_GETBYTE
MOV AX,65535
JMP R_OK
R_GETBYTE:
MOV AL,[R_BYTE]
MOV AH,0
JMP R_OK
; @part OPEN
R_OPEN:
MOV DX,3D00H
JMP R_FILE
; @part CREATE
R_CREATE:
MOV DX,3C00H
JMP R_FILE
; @part FILE
R_FILE:
MOV [R_MODE],DX
MOV [R_NAME],AX
CALL R_FREE
CMP BX,0
JNE R_HAVESLOT
JMP R_FAIL
R_HAVESLOT:
MOV DX,[R_NAME]
MOV CX,0
MOV AX,[R_MODE]
INT 21H
JAE R_FILEGOOD
JMP R_FAIL
R_FILEGOOD:
INC AX
MOV DX,[R_MODE]
CMP DX,3C00H
JNE R_READSLOT
ADD AX,8000H
R_READSLOT:
MOV BX,[R_SLOT]
MOV [BX],AX
MOV AX,[R_NUMBER]
JMP R_OK
R_FREE:
MOV BX,R_HANDLES
MOV CX,1
R_NEXTSLOT:
MOV AX,[BX]
CMP AX,0
JE R_SLOTFOUND
ADD BX,2
INC CX
CMP CX,9
JB R_NEXTSLOT
MOV BX,0
RET
R_SLOTFOUND:
MOV [R_SLOT],BX
MOV [R_NUMBER],CX
RET
; @part FIND
R_FIND:
CMP BX,1
JB R_BADHANDLE
CMP BX,8
JA R_BADHANDLE
DEC BX
ADD BX,BX
ADD BX,R_HANDLES
MOV [R_SLOT],BX
MOV BX,[BX]
CMP BX,0
JE R_BADHANDLE
MOV AX,1
CMP BX,8000H
JB R_HANDLEKIND
AND BX,7FFFH
MOV AX,2
R_HANDLEKIND:
DEC BX
RET
R_BADHANDLE:
MOV AX,0
RET
; @part READ
R_READ:
MOV [R_COUNT],AX
MOV [R_BUFFER],DX
CALL R_FIND
CMP AX,1
JE R_READVALID
JMP R_FAIL
R_READVALID:
MOV CX,[R_COUNT]
CMP CX,0
JNE R_READMORE
MOV AX,0
JMP R_OK
R_READMORE:
MOV DX,[R_BUFFER]
MOV AH,3FH
INT 21H
JAE R_READGOOD
JMP R_FAIL
R_READGOOD:
JMP R_OK
; @part WRITE
R_WRITE:
MOV [R_COUNT],AX
MOV [R_BUFFER],DX
CALL R_FIND
CMP AX,2
JE R_WRITEVALID
JMP R_FAIL
R_WRITEVALID:
MOV CX,[R_COUNT]
CMP CX,0
JNE R_WRITEMORE
MOV AX,0
JMP R_OK
R_WRITEMORE:
MOV DX,[R_BUFFER]
MOV AH,40H
INT 21H
JAE R_WRITECOUNT
JMP R_FAIL
R_WRITECOUNT:
MOV DX,[R_COUNT]
CMP AX,DX
JE R_WRITEGOOD
JMP R_ERROR
R_WRITEGOOD:
JMP R_OK
; @part CLOSE
R_CLOSE:
MOV BX,AX
CALL R_FIND
CMP AX,0
JNE R_CLOSEVALID
JMP R_FAIL
R_CLOSEVALID:
MOV AH,3EH
INT 21H
JAE R_CLOSEGOOD
JMP R_FAIL
R_CLOSEGOOD:
MOV BX,[R_SLOT]
MOV AX,0
MOV [BX],AX
JMP R_OK
; @part BYTE
R_BYTE:
DB 0
; @part FILEDATA
R_MODE:
DW 0
R_NAME:
DW 0
R_SLOT:
DW 0
R_NUMBER:
DW 0
R_HANDLES:
DW 0,0,0,0,0,0,0,0
; @part TRANSFERDATA
R_COUNT:
DW 0
R_BUFFER:
DW 0
